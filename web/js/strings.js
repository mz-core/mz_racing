  let current = "pt-BR";
  function normalize(value) {
    const locale = String(value || "").replace("_", "-");
    return locale === "en" || locale === "en-US" ? "en-US" : "pt-BR";
  }
  function set(value) {
    current = normalize(value);
    document.documentElement.lang = current;
    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const key = element.dataset.i18n;
      if (dictionaries[current][key]) element.textContent = dictionaries[current][key];
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
      const key = element.dataset.i18nPlaceholder;
      if (dictionaries[current][key]) element.setAttribute("placeholder", dictionaries[current][key]);
    });
    document.getElementById("closeButton")?.setAttribute("aria-label", dictionaries[current].close);
    document.getElementById("organizerCloseButton")?.setAttribute("aria-label", dictionaries[current].close);
  }
  function t(key, values = {}) {
    let text = dictionaries[current][key] || dictionaries["pt-BR"][key] || key;
    Object.entries(values).forEach(([name, value]) => {
      text = text.replaceAll(`{${name}}`, String(value));
    });
    return text;
  }

  window.MZRacingI18n = { set, t, getLocale: () => current };
